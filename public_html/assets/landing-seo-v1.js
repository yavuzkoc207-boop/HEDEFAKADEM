  function normalize(code) {
    if (code === 'kk') return 'kz';
    return code === 'en' || code === 'ru' || code === 'kz' ? code : 'tr';
  }

  function applyLanguage(code) {
    const lang = normalize(code);
    const dict = lang === 'tr' ? TR : I18N[lang];

    elements.forEach((el) => {
      const value = dict[el.dataset.seoT];
      if (value != null) el.textContent = value;
    });

    document.documentElement.lang = lang === 'kz' ? 'kk' : lang;
    document.title = META[lang].title;
    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute('content', META[lang].description);
  }

  document.addEventListener('ha:language-change', (event) => {
    applyLanguage(event.detail && event.detail.language);
  });

  window.addEventListener('storage', (event) => {
    if (event.key === 'ha-language') applyLanguage(event.newValue);
  });

  let initial = 'tr';
  try { initial = localStorage.getItem('ha-language') || 'tr'; } catch (_) {}
  applyLanguage(initial);
